const LAYER_BY_ID: ReadonlyMap<string, SigraLayerDefinition> = new Map(
  SIGRA_LAYERS.map((layer) => [layer.id, layer]),
);

export function isSigraLayerId(value: unknown): value is SigraLayerId {
  return typeof value === "string" && LAYER_BY_ID.has(value);
}

export function getSigraLayer(id: SigraLayerId): SigraLayerDefinition {
  const layer = LAYER_BY_ID.get(id);
  if (!layer) throw new Error(`Capa SIGRA desconocida: ${id}`);
  return layer;
}
