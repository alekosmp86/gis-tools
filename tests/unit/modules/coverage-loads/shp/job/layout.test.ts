import path from "node:path";
import { describe, expect, it } from "vitest";
import {
  assertJobId,
  defaultRootDir,
  isValidJobId,
  jobPaths,
  jobsDir,
  lockPath,
  locksDir,
  newJobId,
} from "@/modules/coverage-loads/shp/job/layout.ts";

const UUID = "0b9a1f3e-5c4d-4e2a-9f10-1234567890ab";

describe("layout", () => {
  describe("isValidJobId / assertJobId", () => {
    it("should accept a lowercase UUID when validating", () => {
      expect(isValidJobId(UUID)).toBe(true);
      expect(assertJobId(UUID)).toBe(UUID);
    });

    it("should accept ids generated by newJobId", () => {
      expect(isValidJobId(newJobId())).toBe(true);
    });

    it.each([
      ["empty", ""],
      ["dot dot", ".."],
      ["traversal", "../../etc/passwd"],
      ["traversal after uuid", `${UUID}/..`],
      ["forward slash", `${UUID}/x`],
      ["backslash", `${UUID}\\x`],
      ["uppercase", UUID.toUpperCase()],
      ["too short", UUID.slice(0, -1)],
      ["too long", `${UUID}0`],
      ["leading space", ` ${UUID}`],
      ["trailing newline", `${UUID}\n`],
      ["non-hex", UUID.replace("0b9a", "zzzz")],
      ["no dashes", UUID.replaceAll("-", "")],
    ])("should reject the id when it is %s", (_label, value) => {
      expect(isValidJobId(value)).toBe(false);
      expect(() => assertJobId(value)).toThrow("Identificador de carga inválido.");
    });

    it.each([[undefined], [null], [123], [{}], [[UUID]]])("should reject non-string input %j", (value) => {
      expect(isValidJobId(value)).toBe(false);
    });
  });

  describe("paths", () => {
    it("should build every job path under the injected root when the id is valid", () => {
      const root = path.join("x", "root");

      const paths = jobPaths(root, UUID);

      const dir = path.join(root, "jobs", UUID);
      expect(paths).toEqual({
        dir,
        upload: path.join(dir, "upload.part"),
        source: path.join(dir, "source.shp"),
        status: path.join(dir, "status.json"),
        statusTmp: path.join(dir, "status.json.tmp"),
        log: path.join(dir, "job.log"),
        cancel: path.join(dir, "cancel.request"),
        startLock: path.join(dir, "start.lock"),
      });
    });

    it("should throw when jobPaths receives a traversal id", () => {
      expect(() => jobPaths("root", "..")).toThrow();
    });

    it("should expose jobs and locks dirs under the root", () => {
      expect(jobsDir("r")).toBe(path.join("r", "jobs"));
      expect(locksDir("r")).toBe(path.join("r", "locks"));
    });

    it.each(["cobertura5g", "wcdma", "nbiot", "lte"] as const)("should build the lock path for table %s", (table) => {
      expect(lockPath("r", table)).toBe(path.join("r", "locks", `${table}.json`));
    });

    it("should throw when the lock table is not a known table", () => {
      expect(() => lockPath("r", "../evil" as never)).toThrow("Tabla destino inválida.");
    });

    it("should default the root to cwd/data/coverage-loads", () => {
      expect(defaultRootDir()).toBe(path.join(process.cwd(), "data", "coverage-loads"));
    });
  });
});
